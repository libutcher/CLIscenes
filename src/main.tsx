/**
 * Player page. Loads a generated demo and renders it.
 *
 *   index.html                          first demo, with a demo picker
 *   index.html?demo=cli-signin          a specific demo
 *   index.html?demo=cli-signin&embed=1  walkthrough only, for iframes
 *   index.html?...&theme=dark           force light or dark (default: follow the system)
 */
import { StrictMode, useEffect, useState } from "react";
import { createRoot } from "react-dom/client";
import { MANIFEST_VERSION, type CompiledDemo, type DemoIndexEntry } from "./core/types.ts";
import { Walkthrough } from "./player/Walkthrough.tsx";
import { initColorScheme } from "./player/colorScheme.ts";
import "./page.css";

const params = new URLSearchParams(location.search);
const embed = params.get("embed") === "1";
initColorScheme(params.get("theme"));
const demosUrl = new URL("demos/", document.baseURI);

type Loaded = { demo: CompiledDemo; baseUrl: string; index: DemoIndexEntry[] };

async function load(requested: string | null): Promise<Loaded> {
  const index: DemoIndexEntry[] = await fetchJson(new URL("index.json", demosUrl));
  const id = requested ?? index[0]?.id;
  if (!id || !index.some((d) => d.id === id)) {
    throw new Error(requested ? `No demo named "${requested}".` : "No demos have been generated yet. Run npm run generate.");
  }
  const baseUrl = new URL(`${id}/`, demosUrl).href;
  const demo: CompiledDemo = await fetchJson(new URL("demo.json", baseUrl));
  if (demo.manifestVersion !== MANIFEST_VERSION) {
    throw new Error(`Demo "${id}" was generated by a different version. Run npm run generate.`);
  }
  return { demo, baseUrl, index };
}

async function fetchJson<T>(url: URL): Promise<T> {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Could not load ${url.pathname} (${response.status}).`);
  return response.json() as Promise<T>;
}

function App() {
  const [result, setResult] = useState<Loaded | Error | null>(null);
  useEffect(() => {
    load(params.get("demo")).then(setResult, (error: unknown) =>
      setResult(error instanceof Error ? error : new Error(String(error))),
    );
  }, []);

  if (result === null) return <p className="cs-loading">Loading walkthrough…</p>;
  if (result instanceof Error) return <p role="alert" className="cs-error">{result.message}</p>;

  if (embed) return <Walkthrough demo={result.demo} baseUrl={result.baseUrl} />;

  return (
    <main className="cs-page">
      <header className="cs-page__header">
        <p className="cs-page__brand">CLIscenes</p>
        <nav aria-label="Demos">
          <ul className="cs-page__demos">
            {result.index.map((d) => (
              <li key={d.id}>
                <a href={`?demo=${d.id}`} aria-current={d.id === result.demo.id ? "page" : undefined}>
                  {d.title}
                </a>
              </li>
            ))}
            <li>
              <a href="embed-example.html">Embedding example</a>
            </li>
          </ul>
        </nav>
      </header>
      <Walkthrough demo={result.demo} baseUrl={result.baseUrl} />
    </main>
  );
}

// Page-level styles (src/page.css) and the color tokens apply under .cs-app.
document.documentElement.classList.add("cs-app");

if (embed) {
  document.documentElement.classList.add("cs-embedded");
  // Tell the host page how tall the walkthrough is, so it can size the iframe.
  // The message contains only a number, so any origin may receive it.
  if (window.parent !== window) {
    const report = () =>
      window.parent.postMessage({ type: "cliscenes:height", height: document.documentElement.scrollHeight }, "*");
    new ResizeObserver(report).observe(document.body);
  }
}
createRoot(document.getElementById("root")!).render(
  <StrictMode>
    <App />
  </StrictMode>,
);
